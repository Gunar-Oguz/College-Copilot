"""
Write docs/DATA_SOURCES.md from the data_sources table and the column comments the
loaders store, so the documentation always matches what is loaded.

Usage (from backend/):
    python document_sources.py
"""

from dotenv import load_dotenv

from database import execute_sql, get_data_sources
from source_data import ROOT_DIR

load_dotenv(ROOT_DIR / ".env")

DOC_PATH = ROOT_DIR / "docs" / "DATA_SOURCES.md"

COLUMNS_SQL = """
SELECT c.column_name, c.data_type,
       col_description(format('%%I', c.table_name)::regclass, c.ordinal_position) AS note
FROM information_schema.columns c
WHERE c.table_schema = 'public' AND c.table_name = %s
ORDER BY c.ordinal_position
"""


def main():
    sources = execute_sql(
        "SELECT d.*, obj_description(format('%%I', d.table_name)::regclass, 'pg_class') AS note "
        "FROM data_sources d ORDER BY source, table_name", ()
    ) if get_data_sources() else []
    lines = [
        "# Data sources",
        "",
        "Generated by `backend/document_sources.py`. The core `schools` and `programs` tables come",
        "from the College Scorecard API (see the README). Every table below has one row per school",
        "unless noted, keyed by `school_id` = IPEDS UNITID = `schools.id`. Rates are decimals",
        "(0.25 = 25%).",
        "",
        "| Table | Source | Data year | Rows | Matched schools |",
        "|---|---|---|---:|---:|",
    ]
    for s in sources:
        lines.append(
            f"| `{s['table_name']}` | [{s['source']}]({s['url']}) | {s['data_year'] or ''} "
            f"| {s['row_count']:,} | {s['matched_schools'] or 0:,} |"
        )
    for s in sources:
        lines += ["", f"## `{s['table_name']}`", "", s["note"] or "", "",
                  f"Loaded {s['loaded_at']:%Y-%m-%d}.", "", "| Column | Type | Description |", "|---|---|---|"]
        for c in execute_sql(COLUMNS_SQL, (s["table_name"],)):
            note = (c["note"] or "").replace("|", "\\|")
            lines.append(f"| `{c['column_name']}` | {c['data_type']} | {note} |")
    DOC_PATH.parent.mkdir(exist_ok=True)
    DOC_PATH.write_text("\n".join(lines) + "\n")
    print(f"Wrote {DOC_PATH} ({len(sources)} tables)")


if __name__ == "__main__":
    main()
